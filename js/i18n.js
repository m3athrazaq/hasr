let lang = 'ar';
export function setLang(l) {
  lang = S[l] ? l : 'ar';
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', el.title); }
}
export const getLang = () => lang;
// "n cases" with Arabic number agreement
export function casesText(n) {
  if (lang !== 'ar') return `${n} ${n === 1 ? 'case' : 'cases'}`;
  if (n === 1) return 'حالة واحدة';
  if (n === 2) return 'حالتان';
  if (n >= 3 && n <= 10) return `${n} حالات`;
  return `${n} حالة`;
}
export function t(k) { return S[lang][k] ?? S.ar[k] ?? k; }
export const fmt = (n) => (Number.isFinite(n) ? Math.round(n).toLocaleString('en-US') : '–');
export function fmtDur(ms) {
  const s = Math.max(0, Math.round(ms / 1000));
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), ss = s % 60;
  return (h ? h + ':' + String(m).padStart(2, '0') : m) + ':' + String(ss).padStart(2, '0');
}
export function fmtTime(ts) {
  if (!ts) return '–';
  const d = new Date(ts);
  return d.toLocaleString(lang === 'ar' ? 'ar-KW-u-nu-latn' : 'en-GB', { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' });
}
export function fmtClock(ts) {
  if (!ts) return '–';
  return new Date(ts).toLocaleTimeString(lang === 'ar' ? 'ar-KW-u-nu-latn' : 'en-GB', { hour: '2-digit', minute: '2-digit', second: '2-digit' });
}
